#!/usr/bin/env python3
"""Build-time font rasteriser for the SOLMARA poster entry.

Runs on the builder's machine only (never shipped as runtime code):
rasterises the system DejaVu Serif Bold at one size with Pillow and
writes a Python source fragment (tools/font_data.inc) holding the
glyph bitmaps as one zlib-compressed, base64 blob plus an index.

Glyph record layout (inside the decompressed blob, per glyph):
    adv_q_hi (1 byte), adv_q_lo (1 byte), w (1 byte), h (1 byte),
    xoff+128 (1 byte), yoff+128 (1 byte), then w*h grayscale bytes
    (0 = transparent, 255 = full ink).
adv_q is the advance width in quarter pixels (16-bit). xoff/yoff are
the glyph bounding-box origin relative to Pillow's default anchor
(left edge of the em box, baseline), so blitting reproduces
Pillow's layout exactly.

Usage: python3 tools/gen_fonts.py
"""
import base64
import zlib

from PIL import Image, ImageDraw, ImageFont

FONT_PATH = "/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf"
SIZE = 120
# Only the characters the poster needs (title + a few extras).
CHARSET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ '.-"

font = ImageFont.truetype(FONT_PATH, SIZE)
records = bytearray()
index = {}
for ch in CHARSET:
    # Render the glyph alone on a generous canvas.
    img = Image.new("L", (SIZE * 2, SIZE * 2), 0)
    d = ImageDraw.Draw(img)
    d.text((SIZE // 2, SIZE // 2), ch, font=font, fill=255)
    bbox = img.getbbox()
    if bbox is None:  # space and friends: no ink, advance only
        adv = int(round(font.getlength(ch) * 4))
        records += bytes([adv >> 8, adv & 255, 0, 0, 128, 128])
        index[ch] = (len(records) - 6, 6)
        continue
    x0, y0, x1, y1 = bbox
    w, h = x1 - x0, y1 - y0
    # Origin of the bitmap relative to Pillow's anchor:
    # anchor is at (SIZE//2, SIZE//2); bitmap top-left is (x0, y0).
    # yoff is measured down from the baseline: baseline y = SIZE//2
    # + ascent, where ascent = font.getmetrics()[0].
    ascent, _descent = font.getmetrics()
    baseline = SIZE // 2 + ascent
    xoff = x0 - SIZE // 2
    yoff = y0 - baseline
    adv = int(round(font.getlength(ch) * 4))
    assert -128 <= xoff < 128 and -128 <= yoff < 128, (ch, xoff, yoff)
    crop = img.crop(bbox)
    start = len(records)
    records += bytes([adv >> 8, adv & 255, w, h, xoff + 128, yoff + 128])
    records += crop.tobytes()
    index[ch] = (start, 6 + w * h)

blob = base64.b64encode(zlib.compress(bytes(records), 9)).decode()
lines = []
lines.append("# generated by tools/gen_fonts.py -- do not edit by hand")
lines.append("CHARSET = %r" % CHARSET)
lines.append("FONT_INDEX = %r" % index)
lines.append("FONT_BLOB_B64 = (")
for i in range(0, len(blob), 76):
    lines.append("    %r" % blob[i:i + 76])
lines.append(")")
with open("tools/font_data.inc", "w") as f:
    f.write("\n".join(lines) + "\n")
print("glyphs:", len(CHARSET), "raw bytes:", len(records),
      "b64 chars:", len(blob))
