def _paeth(a, b, c):
    p = a + b - c
    pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    if pa <= pb and pa <= pc:
        return a
    if pb <= pc:
        return b
    return c


def encode_png():
    raw = bytearray()
    prev = bytearray(W * 3)
    for y in range(H):
        row = bytes(buf[y * W * 3:(y + 1) * W * 3])
        # Candidate filters: None, Up, Paeth. Pick the smallest
        # sum-of-absolute-signed-bytes (cheap compressibility proxy).
        cands = []
        cands.append((0, row))
        up = bytes((v - prev[i]) & 255 for i, v in enumerate(row))
        cands.append((2, up))
        pa = bytearray(W * 3)
        for i, v in enumerate(row):
            a = row[i - 3] if i >= 3 else 0
            b = prev[i]
            c = prev[i - 3] if i >= 3 else 0
            pa[i] = (v - _paeth(a, b, c)) & 255
        cands.append((4, bytes(pa)))

        def _cost(fdata):
            s = 0
            for v in fdata:
                s += v if v < 128 else 256 - v
            return s

        ftype, fdata = min(cands, key=lambda cf: _cost(cf[1]))
        raw.append(ftype)
        raw.extend(fdata)
        prev = bytearray(row)
    comp = zlib.compress(bytes(raw), 9)
    ihdr = struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0)

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr)
           + chunk(b"IDAT", comp) + chunk(b"IEND", b""))
    return png


def main():
    png = encode_png()
    os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
    with open(OUT, "wb") as f:
        f.write(png)
    print("wrote", OUT, len(png), "bytes")


