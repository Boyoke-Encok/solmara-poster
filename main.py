W = H = SIZE
buf = bytearray(W * H * 3)


def _lerp(a, b, t):
    return a + (b - a) * t


def _mix(c0, c1, t):
    return (int(_lerp(c0[0], c1[0], t)),
            int(_lerp(c0[1], c1[1], t)),
            int(_lerp(c0[2], c1[2], t)))


def blend(x, y, r, g, b, a):
    """Blend colour (r, g, b) with coverage a (0..255) onto pixel x, y."""
    if a <= 0 or x < 0 or x >= W or y < 0 or y >= H:
        return
    i = (y * W + x) * 3
    if a >= 255:
        buf[i] = r
        buf[i + 1] = g
        buf[i + 2] = b
        return
    ia = 255 - a
    buf[i] = (r * a + buf[i] * ia) // 255
    buf[i + 1] = (g * a + buf[i + 1] * ia) // 255
    buf[i + 2] = (b * a + buf[i + 2] * ia) // 255


def hline(y, x0, x1, r, g, b, a=255):
    """Horizontal span with fractional end coverage (anti-aliased)."""
    if y < 0 or y >= H or x1 <= x0:
        return
    xs = max(x0, 0.0)
    xe = min(x1, float(W))
    if xe <= xs:
        return
    i0 = int(xs)
    i1 = int(xe)
    if i0 == i1:
        blend(i0, y, r, g, b, int(a * (xe - xs)))
        return
    blend(i0, y, r, g, b, int(a * (i0 + 1 - xs)))
    for x in range(i0 + 1, i1):
        blend(x, y, r, g, b, a)
    if xe > i1:
        blend(i1, y, r, g, b, int(a * (xe - i1)))


def fill_poly(points, color, alpha=255):
    """Scanline polygon fill with fractional edge coverage."""
    r, g, b = color
    ys = [p[1] for p in points]
    y0 = max(0, int(min(ys)))
    y1 = min(H - 1, int(max(ys)) + 1)
    n = len(points)
    for y in range(y0, y1 + 1):
        yc = y + 0.5
        xs = []
        for i in range(n):
            x_a, y_a = points[i]
            x_b, y_b = points[(i + 1) % n]
            if (y_a <= yc < y_b) or (y_b <= yc < y_a):
                t = (yc - y_a) / (y_b - y_a)
                xs.append(x_a + t * (x_b - x_a))
        xs.sort()
        for k in range(0, len(xs) - 1, 2):
            hline(y, xs[k], xs[k + 1], r, g, b, alpha)


def disc(cx, cy, rad, color, alpha=255):
    """Filled disc with anti-aliased edge."""
    r, g, b = color
    y0 = max(0, int(cy - rad - 1))
    y1 = min(H - 1, int(cy + rad + 1))
    for y in range(y0, y1 + 1):
        dy = (y + 0.5) - cy
        dx = (rad * rad - dy * dy) ** 0.5 if abs(dy) < rad else 0.0
        if dx > 0:
            hline(y, cx - dx, cx + dx, r, g, b, alpha)


def glow(cx, cy, rad, color, peak):
    """Soft radial glow: alpha falls off quadratically to rad."""
    r, g, b = color
    x0 = max(0, int(cx - rad))
    x1 = min(W - 1, int(cx + rad))
    y0 = max(0, int(cy - rad))
    y1 = min(H - 1, int(cy + rad))
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            d2 = (x - cx) ** 2 + (y - cy) ** 2
            if d2 < rad * rad:
                t = 1.0 - d2 / (rad * rad)
                blend(x, y, r, g, b, int(peak * t * t))


