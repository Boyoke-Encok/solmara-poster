_FONT = zlib.decompress(base64.b64decode(FONT_BLOB_B64))


def _glyph(ch):
    off, ln = FONT_INDEX[ch]
    rec = _FONT[off:off + ln]
    adv = ((rec[0] << 8) | rec[1]) / 4.0
    w, h = rec[2], rec[3]
    xoff, yoff = rec[4] - 128, rec[5] - 128
    return adv, w, h, xoff, yoff, rec[6:]


def text_width(text, tracking=0):
    total = 0.0
    for ch in text:
        adv, _, _, _, _, _ = _glyph(ch)
        total += adv + tracking
    return total - tracking if text else 0.0


def draw_text(text, cx, baseline_y, color, tracking=14, shadow=None):
    """Draw centred text; shadow is an (dx, dy, colour, alpha) tuple."""
    w = text_width(text, tracking)
    x = cx - w / 2.0
    if shadow is not None:
        sdx, sdy, scol, sa = shadow
        _draw_text_at(text, x + sdx, baseline_y + sdy, scol, tracking, sa)
    _draw_text_at(text, x, baseline_y, color, tracking, 255)


def _draw_text_at(text, x, baseline_y, color, tracking, alpha):
    r, g, b = color
    pen = x
    for ch in text:
        adv, w, h, xoff, yoff, px = _glyph(ch)
        gx = int(round(pen)) + xoff
        gy = int(round(baseline_y)) + yoff
        for row in range(h):
            yy = gy + row
            if yy < 0 or yy >= H:
                continue
            for col in range(w):
                a = px[row * w + col]
                if a:
                    blend(gx + col, yy, r, g, b, (a * alpha) // 255)
        pen += adv + tracking


